/**
 * Prepare a ready-made mascot for the site.
 *
 *   node build-mascot-model.mjs <source.glb> <id> [config.json]
 *
 * 1. compresses the sculpt with meshopt (EXT_meshopt_compression — the
 *    decoder ships inside three, so nothing is fetched at runtime)
 * 2. writes website/assets/mascots/<id>/model.glb   (the sellable asset)
 * 3. writes website/assets/mascots/<id>/model.js    (base64 wrapper, so the
 *    stage can load it from file:// as well as http://)
 * 4. copies the studio config next to it
 */
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '../..');
const source = process.argv[2];
const id = process.argv[3];
const configPath = process.argv[4];

if (!source || !id) {
  console.error('usage: node build-mascot-model.mjs <source.glb> <id> [config.json]');
  process.exit(1);
}

const outDir = path.join(ROOT, 'website/assets/mascots', id);
mkdirSync(outDir, { recursive: true });

const glbOut = path.join(outDir, 'model.glb');
const tmp = path.join(outDir, '.tmp.glb');

execFileSync(
  'npx',
  ['--yes', '@gltf-transform/cli@4', 'meshopt', source, tmp],
  { stdio: 'inherit', cwd: ROOT }
);
copyFileSync(tmp, glbOut);
const { unlinkSync } = await import('node:fs');
unlinkSync(tmp);

const bytes = readFileSync(glbOut);
const base64 = bytes.toString('base64');

writeFileSync(
  path.join(outDir, 'model.js'),
  `/* ${id} — ready-made mascot model. Generated by marketing/tools/build-mascot-model.mjs.
   * Base64 so the stage loads it from file:// too — no fetch, no CORS. */
window.__FLYMASCOT_MODELS__ = window.__FLYMASCOT_MODELS__ || {};
window.__FLYMASCOT_MODELS__[${JSON.stringify(id)}] = ${JSON.stringify(base64)};
`
);

if (configPath) copyFileSync(configPath, path.join(outDir, 'config.json'));

const kb = (n) => `${(n / 1024).toFixed(0)} KB`;
console.log(`model.glb  ${kb(bytes.length)}  -> website/assets/mascots/${id}/model.glb`);
console.log(`model.js   ${kb(base64.length)}  -> website/assets/mascots/${id}/model.js`);
